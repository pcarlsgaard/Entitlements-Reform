import { eligiblePopulationMillions } from './demographics'
import type { ModelAssumptions } from './types'
import type { HealthPolicySettings } from '../tax/model/health'

/**
 * Universal, risk-adjusted private-plan premium support. The benchmark is a
 * deliberately transparent scenario, not an observed nationwide bid auction.
 * All prices are 2026 dollars at inception; both the benchmark and rural
 * payment are trended in nominal dollars. Individual premiums grow with CPI.
 *
 * The gross reference bid includes medical claims, insurance administration,
 * risk adjustment and reinsurance. Reinsurance transfers are NOT extra costs.
 * No advance-funding asset is generated by billing members from birth.
 */
export interface UniversalHealthYear {
  year: number
  populationMillions: number
  averageBidMonthly: number
  benchmarkMonthly: number
  memberPremiumMonthly: number
  grossBenchmarkBillions: number
  memberContributionsBillions: number
  publicBenchmarkBillions: number
  ruralSupportBillions: number
  federalOutlayBillions: number
}

export function universalHealthForYear(
  year: number, assumptions: ModelAssumptions, settings: HealthPolicySettings,
): UniversalHealthYear {
  const elapsed = year - assumptions.reformYear
  const cpi = (1 + assumptions.inflation) ** elapsed
  const healthcareGrowth = (1 + settings.universalBidRealGrowth) ** elapsed
  const averageBidMonthly = settings.universalAverageBidMonthly2026 * cpi * healthcareGrowth
  const benchmarkMonthly = averageBidMonthly * (
    settings.universalBenchmark === 'secondLowest' ? settings.universalSecondLowestBidFactor : 1
  )
  const memberPremiumMonthly = Math.min(
    benchmarkMonthly, settings.universalMemberPremiumMonthly2026 * cpi,
  )
  const populationMillions = eligiblePopulationMillions(year, 0, assumptions)
  // Millions of people * dollars per year / 1000 = billions of dollars.
  const grossBenchmarkBillions = populationMillions * benchmarkMonthly * 12 / 1000
  const memberContributionsBillions = populationMillions * memberPremiumMonthly * 12 / 1000
  const publicBenchmarkBillions = grossBenchmarkBillions - memberContributionsBillions
  const ruralSupportBillions = settings.universalRuralSupportBillions2026 * cpi * healthcareGrowth
  return {
    year, populationMillions, averageBidMonthly, benchmarkMonthly, memberPremiumMonthly,
    grossBenchmarkBillions, memberContributionsBillions, publicBenchmarkBillions,
    ruralSupportBillions, federalOutlayBillions: publicBenchmarkBillions + ruralSupportBillions,
  }
}
